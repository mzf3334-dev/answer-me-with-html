#!/usr/bin/env node
// Convert an upstream (main) tree into the zh-TW edition tree.
// Run from the repo root of a clean main checkout. Deterministic: running it
// on an already converted tree changes nothing (check.mjs gate 4 verifies).
//
// Steps: rename zh-CN docs to zh-TW, OpenCC (cn -> tw2) over reader-facing
// content, rebrand the repo slug to doggy8088/answer-me-with-html, point the
// website's Chinese edition at zh-TW, adapt the tests that name the Chinese
// files, and apply the settled Taiwan vocabulary fixes.
//
// Requires: opencc-cli (@willh/opencc-cli, doggy8088/opencc-cli) on PATH,
// or set OPENCC=/path/to/opencc-cli.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { GLOBAL_VOCAB, PHRASES } from './vocab.mjs';
import path from 'node:path';

const root = process.cwd();
const OCC = process.env.OPENCC || 'opencc-cli';
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const write = (f, t) => fs.writeFileSync(path.join(root, f), t);
const exists = (f) => fs.existsSync(path.join(root, f));
const sub = (f, pairs) => {
  if (!exists(f)) return;
  let t = read(f);
  const orig = t;
  for (const [a, b] of pairs) t = t.split(a).join(b);
  if (t !== orig) write(f, t);
};
const globMd = (dir, suffix) =>
  fs.readdirSync(path.join(root, dir), { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(suffix))
    .map((e) => path.join(dir, e.name));

// 1) Renames: no zh-CN file survives.
const RENAMES = [
  ['README.zh-CN.md', 'README.zh-TW.md'],
  ['docs/reference.zh-CN.md', 'docs/reference.zh-TW.md'],
  ['docs/compare.zh-CN.md', 'docs/compare.zh-TW.md'],
  ['docs/video.zh-CN.md', 'docs/video.zh-TW.md'],
  ['docs/elevenlabs.zh-CN.md', 'docs/elevenlabs.zh-TW.md'],
];
for (const [a, b] of RENAMES) if (exists(a)) fs.renameSync(path.join(root, a), path.join(root, b));

// 2) Content files converted with OpenCC.
const CONTENT = [
  'README.zh-TW.md',
  ...globMd('docs', '.zh-TW.md'),
  'site/i18n/zh.js',
  ...globMd('site/presets', '.zh.md'),
  ...globMd('site/presets/components', '.zh.md'),
  'examples/tcp.md', 'examples/video-tcp.md', 'examples/architecture.md',
  ...globMd('changelog', '.md'),
  'bench/README.md',
  'locale/zh.json',
  ...globMd('marketplace/themes', '.json'),
  'docs/demo/demo.html',
  'skills/answer-me-with-html/SKILL.md',
  'skills/answer-me-with-html/references/video.md',
  '.gitignore', '.gitattributes', '.github/workflows/ci.yml',
].filter(exists);

for (const f of CONTENT) {
  const tmp = `${f}.zh-tw-tmp`;
  execFileSync(OCC, ['-f', 'cn', '-t', 'tw2', '-i', f, '-o', tmp], { cwd: root, stdio: 'inherit' });
  const out = read(tmp);
  if (!out && read(f)) throw new Error(`opencc produced empty output for ${f}`);
  write(f, out);
  fs.unlinkSync(path.join(root, tmp));
}
// tw2 renders ffmpeg 编码 (encode) as 寫程式 in the CI comment; restore.
sub('.github/workflows/ci.yml', [['ffmpeg 寫程式', 'ffmpeg 編碼']]);

// 3) Rebrand: installs and update checks point at the fork.
const ALL = [];
const walk = (d) => {
  for (const e of fs.readdirSync(path.join(root, d), { withFileTypes: true })) {
    if (['.git', 'node_modules', 'dist'].includes(e.name)) continue;
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(md|js|mjs|json|yml|yaml|html|txt|css)$/.test(e.name) || e.name === 'LICENSE') ALL.push(p);
  }
};
walk('.');
// The bundle is regenerated by `npm run build` in sync.sh; do not hand-edit.
for (const f of ALL.filter((f) => !f.endsWith('scripts/am.mjs') && !f.startsWith('scripts/zh-tw/'))) {
  sub(f, [['QingYunA/answer-me-with-html', 'doggy8088/answer-me-with-html']]);
}
// Tests that hard-code the project URL follow the rebrand.
sub('test/render.test.js', [['QingYunA\\/answer-me-with-html', 'doggy8088\\/answer-me-with-html']]);
sub('test/rtl.test.js', [['QingYunA\\/answer-me-with-html', 'doggy8088\\/answer-me-with-html']]);

// 4) Filename references and link labels.
const REF_FILES = [
  'README.md', 'README.zh-TW.md', 'CONTRIBUTING.md', '.github/pull_request_template.md',
  'docs/compare.md', 'docs/elevenlabs.md', 'docs/reference.md', 'docs/video.md',
  'docs/reference.zh-TW.md', 'docs/video.zh-TW.md',
  'test/always-rule.test.js', 'test/diagram-tokens.test.js',
  ...globMd('changelog', '.md'),
];
for (const f of REF_FILES) sub(f, [['zh-CN.md', 'zh-TW.md']]);
sub('README.md', [['<a href="README.zh-TW.md">简体中文</a>', '<a href="README.zh-TW.md">繁體中文</a>']]);
for (const f of ['docs/compare.md', 'docs/elevenlabs.md', 'docs/reference.md', 'docs/video.md']) {
  if (!exists(f)) continue;
  write(f, read(f).replace(/\[简体中文\]\(([a-z]+)\.zh-TW\.md\)/g, '[繁體中文]($1.zh-TW.md)'));
}
// Changelog wording now follows the Traditional labels.
sub('CONTRIBUTING.md', [['src/languages/zh.js` and of `docs/reference.zh-TW.md`', 'src/languages/zh-Hant.js` and of `docs/reference.zh-TW.md`']]);
// always-rule test: its regexes name the converted README's wording.
sub('test/always-rule.test.js', [['汇报', '彙報'], ['页面', '頁面']]);
// site test: its expectations name the Chinese edition's locale and labels.
// (zh-CN is the only zh-CN string in this file, all in hreflang slots.)
sub('test/site.test.js', [['zh-CN', 'zh-TW'], ['制作主题', '製作主題'], ['主题', '主題'], ['复制给你的 agent', '複製給你的 agent'],
  ['字体: Bangers', '字體: Bangers'], ['旧版本（手动安装）', '舊版本（手動安裝）'],
  ['运行 am theme add ${name} --use。如果版本低于 0.5.3，改为把 ${url} 保存为 ~/.answer-me-with-html/themes/${name}.json。', '執行 am theme add ${name} --use。如果版本低於 0.5.3，改為把 ${url} 儲存為 ~/.answer-me-with-html/themes/${name}.json。']]);
// language test: the pipeline itself names Simplified forms to detect them.
sub('test/language.test.js', [[`  { dir: 'src/languages/', why: 'the page and player labels of each supported language' },`, `  { dir: 'src/languages/', why: 'the page and player labels of each supported language' },
  { dir: 'scripts/zh-tw/', why: 'the zh-tw pipeline names Simplified forms to detect and replace them' },`]]);

// 5) The website's Chinese edition is zh-TW (URL paths stay /zh/).
sub('site/build.mjs', [["htmlLang: 'zh-CN'", "htmlLang: 'zh-TW'"]]);
sub('site/i18n/zh.js', [["og_locale: 'zh_CN'", "og_locale: 'zh_TW'"]]);
sub('site/i18n/en.js', [["alt_hreflang: 'zh-CN'", "alt_hreflang: 'zh-TW'"], ['切换到中文版', '切換到中文版']]);
for (const f of ['site/template.html', 'site/template-changelog.html', 'site/template-editor.html', 'site/template-theme.html', 'site/template-themes.html']) {
  sub(f, [['hreflang="zh-CN"', 'hreflang="zh-TW"']]);
}
sub('site/src/style.css', [[':lang(zh-CN)', ':lang(zh-TW)']]);
// The fork's site is served from its own GitHub Pages custom domain, and its
// share images are dedicated 1200x630 JPEGs (Facebook-recommended size),
// regenerated by regen-images.mjs and carried over by sync.sh.
sub('site/build.mjs', [["const SITE_URL = 'https://answer-me-with-html.com/'", "const SITE_URL = 'https://answer-me-with-html.gh.miniasp.com/'"],
  ["'plain-vs-skill.png']", "'plain-vs-skill.png', 'og-en.jpg', 'og-zh.jpg']"]]);
sub('site/i18n/en.js', [["og_image: 'text-vs-page.png'", "og_image: 'og-en.jpg'"],
  ['https://answer-me-with-html.com/themes/make.md', 'https://answer-me-with-html.gh.miniasp.com/themes/make.md']]);
sub('site/i18n/zh.js', [["og_image: 'text-vs-page-zh.png'", "og_image: 'og-zh.jpg'"],
  ['https://answer-me-with-html.com/themes/make.md', 'https://answer-me-with-html.gh.miniasp.com/themes/make.md']]);
for (const f of ['site/template.html', 'site/template-changelog.html', 'site/template-editor.html', 'site/template-theme.html', 'site/template-themes.html']) {
  sub(f, [['<meta property="og:image" content="{{SITE_URL}}images/{{og_image}}">',
    '<meta property="og:image" content="{{SITE_URL}}images/{{og_image}}">\n<meta property="og:image:width" content="1200">\n<meta property="og:image:height" content="630">\n<meta property="og:image:type" content="image/jpeg">']]);
}
// The site's own published guides name the site's resources; point them at
// the fork's domain as well (llms.txt is published verbatim).
sub('site/llms.txt', [['https://answer-me-with-html.com/', 'https://answer-me-with-html.gh.miniasp.com/']]);
sub('site/make.md', [['https://answer-me-with-html.com/', 'https://answer-me-with-html.gh.miniasp.com/']]);
// site test: its SITE_URL constant names the fork's domain too, as do the
// robots.txt sitemap line, the catalog index URL and the make.md links.
sub('test/site.test.js', [["const SITE_URL = 'https://answer-me-with-html.com/'", "const SITE_URL = 'https://answer-me-with-html.gh.miniasp.com/'"],
  ['`https://answer-me-with-html.com/themes/${t.name}.json`', '`https://answer-me-with-html.gh.miniasp.com/themes/${t.name}.json`'],
  ["'https://answer-me-with-html.com/themes/make.md'", "'https://answer-me-with-html.gh.miniasp.com/themes/make.md'"]]);
sub('test/site.test.js', [['answer-me-with-html\\\\.com\\\\/sitemap', 'answer-me-with-html\\\\.gh\\\\.miniasp\\\\.com\\\\/sitemap'],
  ['answer-me-with-html\\\\.com\\\\/themes\\\\/make', 'answer-me-with-html\\\\.gh\\\\.miniasp\\\\.com\\\\/themes\\\\/make']]);

// 6) Workflows also run on the default (zh-tw) branch.
for (const f of ['.github/workflows/ci.yml', '.github/workflows/pages.yml', '.github/workflows/release.yml']) {
  sub(f, [['branches: [main]', 'branches: [main, zh-tw]']]);
}

// 7) Taiwan vocabulary fixes on converted content (settled in review).
for (const f of CONTENT) sub(f, [...GLOBAL_VOCAB, ...PHRASES]);
// The reference quotes the Hans word list verbatim (登陸 -> 登錄); keep the quote.
sub('docs/reference.zh-TW.md', [['登陸→登入', '登陸→登錄']]);

console.log(`converted ${CONTENT.length} content files`);
